#!/usr/bin/env python3
"""Paper light diffusers for the knobs' NeoPixels.

    hardware/cad/tools/diffusers.py [out_dir]      (default hardware/laser/diffusers/)

Each knob's Adafruit 4991 carries a NeoPixel that shines at the back of the
outer bezel sheet, through the ring of light slits (KNOB_SLITS in enclosure.fs).
Behind the slits the inner bezel sheet is pocketed, #knobPocket square, so the
encoder can clamp the outer sheet alone. A square of paper in that pocket,
flat against the outer sheet's back, spreads the one bright dot into an even
glow round the whole ring. The encoder's bushing goes through a hole in its
middle, and the encoder's face clamps it in place as the jam nut goes on.

Not part of the Onshape model (paper is not sheet stock), so it is drawn here,
from the same live variables the model uses: #knobPocket for the square,
#boreDia for the hole, #knobCount for how many.

Writes knob-diffuser.dxf (one), knob-diffusers.dxf (a sheet of knobCount plus
spares), preview.png and README.md. Layer CUT only, millimetres, drawn
nominal: paper's kerf is small enough to ignore.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import export_dxf as X  # noqa: E402  (curl, plain, ids)
from test_cuts import CUT, circle, fmt, render, rect, shift, write_dxf  # noqa: E402

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "laser", "diffusers")
CLEAR = 0.25         # mm, each side, inside the pocket: drops in without curling
HOLE_CLEAR = 0.3     # mm, on the bore's diameter: slips over the M7 bushing's thread
SPARES = 4
COLS = 4
GAP = 3.0


def fetch_vars():
    """-> (#knobPocket mm, #boreDia mm, #knobCount), evaluated in the studio."""
    script = ('function(context is Context, queries) { return ['
              'getVariable(context, "knobPocket") / millimeter, getVariable(context, "boreDia") / millimeter, '
              'getVariable(context, "knobCount")]; }')
    d = X.curl("POST", f"{X.API}/partstudios/d/{X.DID}/w/{X.WID}/e/{X.PS}/featurescript",
               {"script": script, "queries": {}})
    pocket, bore, count = X.plain(d["result"])
    return round(pocket, 6), round(bore, 6), int(count)


def main():
    pocket, bore, count = fetch_vars()
    side, hole = pocket - 2 * CLEAR, bore + HOLE_CLEAR
    one = rect(0, 0, side, side) + circle(side / 2, side / 2, hole)
    n = count + SPARES
    rows = -(-n // COLS)
    sheet = []
    for k in range(n):
        sheet += shift(one, (k % COLS) * (side + GAP), (rows - 1 - k // COLS) * (side + GAP))
    W, H = COLS * side + (COLS - 1) * GAP, rows * side + (rows - 1) * GAP
    os.makedirs(OUT, exist_ok=True)
    write_dxf(os.path.join(OUT, "knob-diffuser.dxf"), one)
    write_dxf(os.path.join(OUT, "knob-diffusers.dxf"), sheet)
    render(os.path.join(OUT, "preview.png"), sheet, (W, H))
    with open(os.path.join(OUT, "README.md"), "w") as f:
        f.write(f"""# Knob light diffusers (paper)

Generated by `hardware/cad/tools/diffusers.py` from the Onshape variables — do not
edit by hand; change the variables and re-run.

One square of paper per knob, in the inner bezel sheet's pocket behind it, flat
against the outer sheet's back: it spreads the NeoPixel on the knob's Adafruit
4991 into an even glow through the whole ring of light slits.

| File | What |
|---|---|
| `knob-diffuser.dxf` | one diffuser: {fmt(side)} mm square (the {fmt(pocket)} mm `#knobPocket` less {fmt(CLEAR)} a side), Ø{fmt(hole)} hole (`#boreDia` {fmt(bore)} + {fmt(HOLE_CLEAR)}) |
| `knob-diffusers.dxf` | {n} of them, {COLS} across, {fmt(GAP)} mm apart: {count} knobs + {SPARES} spares, {fmt(W)} × {fmt(H)} mm |

DXF R12, millimetres, layer `CUT`, drawn nominal (paper's kerf is small enough to
ignore).

**Paper:** plain 80–120 gsm copy paper, or tracing paper / drafting vellum for a
brighter ring. If the LED still shows as a spot, stack two. On the xTool P2 cut
paper at low power and high speed, with air assist on gently or off so the
pieces don't blow away; tape the sheet down at its edges.

**Fitting:** with the encoder out, drop the square into the pocket, push the
encoder's bushing through the hole from behind, and put the jam nut on from the
front: the encoder's face clamps the paper against the outer sheet. The hole is
not keyed and the square fits either way round.

![All diffusers](preview.png)
""")
    print(f"{n} diffusers, {fmt(side)} mm square, Ø{fmt(hole)} hole -> {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
