// Adapted for Patternflood's 128 x 128 panel (2026-10-28): the published 128 x 64 frame
// lies on its side, so the 13 hand-drawn walk-cycle frames are drawn turned a quarter
// anticlockwise (the old right edge is the top): the elephant stands upright, head and
// ears up, 128 px tall, centred in the square. The breathing rings now come in from the
// whole square: the scaled-silhouette field (how many silhouette radii a pixel sits out
// from frame 0's centroid, along the ray through it, the same rule the original baked
// into OWN_SCALE) is computed at setup for the turned 128 x 128 frame, so the corners,
// up to ~3.7 radii out, sit on rings too. Past 1.6 radii the outline eases into a copy
// of itself smoothed over a few degrees, so its one-pixel notches don't fan out into
// sawteeth by the corners. Nine rings 0.35 apart instead of four, so the spacing,
// closing speed and inhale/exhale timing at any spot are the original's. Where the
// published frame cut things at its edge, the drawing is finished off: the ground
// shadow's cut end gets a ragged rounded tail like its other end, and an arm reaching
// the old frame edge (7th to 10th frames) gets a rounded, outlined paw tip. Palette, knobs, acid
// noise, aberration and kaleidoscope are the original's, with the aberration direction
// and mirror axis turned with the picture.
//
// ----- original notes -----
// Ported from mesto_elephant_walk.js (browser Pattern Lab preview) to the
// ESP32-S3 firmware. Not a procedural formula: the walk cycle is 13
// hand-drawn frames baked at build time (RLE-packed, see FRAME*_RLE below),
// same idea as the JS ASCII-grid sprite. On top of the sprite:
//
//  - Concentric "breathing" rings converge INTO the elephant, shaped like
//    one reference silhouette (frame 0) scaled toward its own centroid —
//    not a distance field, which read as jagged at concave spots (between
//    the legs/ears). OWN_SCALE below holds that scaled-silhouette field.
//  - Ring closing speed is tied to the walk cycle's own frame position
//    (frames 3-8 1-indexed = "inhale", speeds up; frames 9..3 wrapping =
//    "exhale", slows back down) — not an independent clock.
//  - Knob A: hue-rotates the whole palette together.
//  - Knob B: multiplies the rings' closing speed.
//  - Knob C: one "how much madness" dial — acid noise (lets the ring-blend
//    math overshoot its normal 0..1 range, which wraps through uint8 for a
//    glitch) -> chromatic aberration -> 6-way kaleidoscope, overlapping so
//    it builds smoothly rather than switching.
//  - Knob D: spins the aberration direction and the kaleidoscope's mirror
//    axis together.
