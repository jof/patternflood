// decode one RLE frame, turned, into codes[] (everything off the sprite is G)
static void decodeTurned(int frameIdx) {
    memset(codes, 0, sizeof(codes));
    const uint8_t* rle = FRAME_RLE[frameIdx];
    const uint16_t rleLen = FRAME_RLE_LEN[frameIdx];
    int x = 0, y = 0;
    for (uint16_t p = 0; p < rleLen && y < SPR_H; p++) {
        const uint8_t sym = rle[p] >> 5;
        int run = (rle[p] & 0x1F) + 1;
        while (run-- > 0 && y < SPR_H) {
            codes[(SPR_Y0 + SPR_W - 1 - x) * FRAME_W + SPR_X0 + y] = sym;
            if (++x == SPR_W) { x = 0; y++; }
        }
    }
}

