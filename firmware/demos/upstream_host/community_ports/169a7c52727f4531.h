namespace L1 {
  static float t = 0.0f;
  static float smoothHeight = 0.324f;

  void setup() {
    PFMath::buildSinLUT();
    t = 0.0f;
    smoothHeight = 0.324f;
  }

  void update(float dt, const InputFrame& input) {
    (void)input;
    float speed = knobVal[0];
    t += dt * speed;
    if (t >= TWO_PI * 20.0f) {
      t -= TWO_PI * 20.0f;
    }

    // 원래 범위(0.2 ~ 0.95)는 100% 보존하면서, 
    // 급격한 변화 없이 미세하고 연속적으로 조절되도록 댐핑(EMA) 필터 적용
    float targetHeight = knobVal[1];
    if (targetHeight < 0.2f) targetHeight = 0.2f;
    if (targetHeight > 0.95f) targetHeight = 0.95f;

    smoothHeight += (targetHeight - smoothHeight) * (1.0f - expf(-3.5f * dt));
  }

  void draw() {
    const float height = smoothHeight;

    int bands = (int)knobVal[2];
    if (bands < 2) bands = 2;

    float pixelScale = floorf(knobVal[3]);
    if (pixelScale < 4.0f) pixelScale = 4.0f;

    const float minV = 0.18f;
    const float foamWidth = 0.12f;

    const float aspectTilt = 0.577350269f * ((float)FRAME_W / (float)FRAME_H);

    const float invW = 1.0f / (float)FRAME_W;
    const float invH = 1.0f / (float)FRAME_H;
    const float invBands1 = 1.0f / (float)(bands - 1);
    const float t2Step = floorf(t * 2.0f) * 0.2f;
    const float t35 = t * 3.5f;

    for (int y = 0; y < FRAME_H; y++) {
      float ny = (float)y * invH;

      for (int x = 0; x < FRAME_W; x++) {
        float nx = (float)x * invW;

        float pixelX = floorf(nx * pixelScale) / pixelScale;

        float shoreTilt = -aspectTilt * (pixelX - 0.5f);

        float shoreY = 0.08f + height * 0.82f +
                       PFMath::fastSin(pixelX * PI * 3.0f + t2Step) * 0.04f +
                       shoreTilt;

        if (ny > shoreY) {
          L1_setValue(x, y, 0.0f);
          continue;
        }

        float depthRatio = ny / shoreY;

        float wavePattern = PFMath::fastSin(
          depthRatio * 12.0f - t35 + PFMath::fastSin(pixelX * 8.0f)
        );

        float rawV = minV + depthRatio * 0.45f + wavePattern * 0.12f;
        if (rawV < minV) rawV = minV;
        if (rawV > 0.85f) rawV = 0.85f;

        float normalized = (rawV - minV) / (0.85f - minV);
        float qStep = floorf(normalized * (float)bands) * invBands1;
        float v = minV + qStep * 0.67f;

        if (fabsf(wavePattern - 0.75f) < foamWidth) {
          v = 1.0f;
        }

        if (ny > shoreY - 0.02f) {
          float fade = (shoreY - ny) / 0.02f;
          float clampFade = (fade < 0.0f) ? 0.0f : fade;
          v *= clampFade;
        }

        if (v < 0.0f) v = 0.0f;
        if (v > 1.0f) v = 1.0f;

        L1_setValue(x, y, v);
      }
    }
  }
}
