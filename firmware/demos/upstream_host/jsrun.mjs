// Run the community's JavaScript-only patterns as upstream's Pattern Lab does, with
// upstream's own harness (PatternRuntime, @knobs, @matrix, @ramp), for pfd/community.py.
//
//   node jsrun.mjs bundle SRC                    (sync, on ash: node >= 22.6) SRC/web/**/*.ts -> SRC/web/harness.js
//   node jsrun.mjs serve SRC                     requests on stdin, frames on stdout (the demo process's child)
//   node jsrun.mjs check SRC ID FILE NAME FRAMES SHOTS OUT [WxH]   (SHOTS: frames to keep, "30,90,...")
//                                                one version of a pattern through the scripted player -> a JSON line
//
// Patterns run in this process's own realm: a vm context would isolate them, but makes a
// frame some 80 times slower (every Math.sin goes through the context's global
// interceptor). Isolation is the process's instead: community.py's node_argv() runs it
// under node's permission model (reads only, no writes, child processes, workers or
// addons) in a network namespace of its own, with no network at all. lockdown() takes
// the network globals away too, before any pattern code is seen. A pattern that never
// returns is the caller's to kill.
//
// Protocol (serve): one JSON line per request, one JSON line per reply.
//   {"op":"load","key":K,"file":PATH[,"matrix":[W,H]]}
//                                               -> {"ok":true,"w":W,"h":H} | {"ok":false,"error":...}
//     "matrix" overrides the script's @matrix: the same pattern on a bigger display.
//   {"op":"frame","key":K,"dt":S,"d":[4],"p":[4],"h":[4]}
//                                               -> {"ok":true} then W*H*3 bytes of RGB | {"ok":false,"error":...}
// A frame for a pattern no longer held (LIVE) answers {"ok":false,"error":"not loaded"}: load it again.
// License: MIT
import { readFileSync, writeFileSync, readSync, writeSync } from "node:fs";
import { join } from "node:path";
import vm from "node:vm";

// Patterns kept alive at once. A menu session visits dozens, and holding them all ran a
// Pi 5's node into its heap limit; one evicted is loaded again, from the start.
const LIVE = 8;
const NOT_LOADED = "not loaded";

// The harness's modules, in dependency order, as community.py fetches them.
const MODULES = ["shared/constants", "pattern/controls", "pattern/knobs", "pattern/matrix",
                 "pattern/harness", "pattern/ramp", "community/knobs"];

// ---- bundle: the type-stripped modules as one script, each in its own scope
async function bundle(src) {
  const { stripTypeScriptTypes } = await import("node:module");
  const parts = [];
  for (const mod of MODULES) {
    let code = stripTypeScriptTypes(readFileSync(join(src, "web", mod + ".ts"), "utf8"), { mode: "strip" });
    const names = [];
    code = code.replace(/import\s*\{([^}]*)\}\s*from\s*"@\/lib\/([^"]+)";?/g, (_, list, from) => {
      const ids = list.split(",").map((s) => s.trim()).filter(Boolean).join(", ");
      return ids ? `const { ${ids} } = __m[${JSON.stringify(from)}];` : "";
    });
    if (/^\s*import\s/m.test(code)) throw new Error(`${mod}: an import this bundler doesn't follow`);
    code = code.replace(/^export\s+((?:async\s+)?(?:function\*?|const|let|class))\s+(\w+)/gm, (_, kind, name) => {
      names.push(name);
      return `${kind} ${name}`;
    });
    code = code.replace(/^export\s*\{([^}]*)\};?/gm, (_, list) => {
      names.push(...list.split(",").map((s) => s.trim()).filter(Boolean));
      return "";
    });
    if (/^\s*export\s/m.test(code)) throw new Error(`${mod}: an export this bundler doesn't follow`);
    parts.push(`__m[${JSON.stringify(mod)}] = (() => {\n${code}\nreturn { ${names.join(", ")} };\n})();`);
  }
  const out = `// Generated by jsrun.mjs from upstream's web/src/lib. Do not edit.\nvar __m = {};\n${parts.join("\n")}\n__m;\n`;
  writeFileSync(join(src, "web", "harness.js"), out);
}

// ---- running patterns
function harness(src) {
  return vm.runInThisContext(readFileSync(join(src, "web", "harness.js"), "utf8"), { filename: "harness.js" });
}

function lockdown() {
  for (const name of ["fetch", "WebSocket", "EventSource", "XMLHttpRequest", "WebAssembly"]) delete globalThis[name];
}

class Pattern {
  constructor(m, file, matrix) {
    const code = readFileSync(file, "utf8");
    const size = matrix ? { width: matrix[0], height: matrix[1] } : m["pattern/matrix"].matrixFromCode(code);
    this.m = m;
    this.rt = new m["pattern/harness"].PatternRuntime(size.width, size.height);
    this.knobs = m["community/knobs"].knobSetupFromCode(code);       // the cards' start: each knob mid-range
    this.step = this.knobs.ranges.map((r) => m["pattern/controls"].knobDetentStep(r));
    const ramp = m["pattern/ramp"].parseRampAnnotation(code);
    if (ramp) {
      this.rt.setRamp({ mode: ramp.mode, wrap: ramp.wrap, stops: ramp.stops.map((s) => ({
        position: s.position, color: [1, 3, 5].map((i) => parseInt(s.color.slice(i, i + 2), 16)) })) });
      this.rt.recolor = ramp.recolor;
    }
    const r = this.rt.loadCode(code);
    this.info = r.ok ? { ok: true, w: size.width, h: size.height } : { ok: false, error: r.error };
    this.rgb = new Uint8Array(size.width * size.height * 3);
    this.time = 0;
  }

  frame(dt, d, p, h) {
    const k = this.knobs;
    for (let i = 0; i < 4; i++) {
      const [lo, hi] = k.ranges[i];
      k.values[i] = Math.min(hi, Math.max(lo, k.values[i] + (+d[i] || 0) * this.step[i]));   // held to the range, as PFParams
    }
    this.time += dt;
    const input = this.m["pattern/harness"].createIdleInput(d.map((v) => +v || 0), {
      knobValues: k.values.slice(), knobRanges: k.ranges,
      knobNormalized: this.m["community/knobs"].normalizedKnobs(k.values, k.ranges),
      btnPressed: p.map(Boolean), btnHeld: h.map(Boolean) });
    const r = this.rt.renderFrame(dt, this.time, input);
    if (!r.ok) return r.error || "error";
    const src = this.rt.data, out = this.rgb;
    for (let i = 0, j = 0; j < out.length; i += 4, j += 3) {      // alpha over black
      const a = src[i + 3];
      if (a === 255) { out[j] = src[i]; out[j + 1] = src[i + 1]; out[j + 2] = src[i + 2]; }
      else { out[j] = src[i] * a / 255; out[j + 1] = src[i + 1] * a / 255; out[j + 2] = src[i + 2] * a / 255; }
    }
    return "";
  }
}

const message = (e) => String(e && e.message || e).split("\n")[0];

// ---- serve: synchronous lines in, synchronous replies out
function* lines() {
  const buf = Buffer.alloc(65536);
  let pending = "";
  for (;;) {
    let n;
    try {
      n = readSync(0, buf, 0, buf.length, null);
    } catch (e) {
      if (e.code === "EAGAIN") continue;
      if (e.code === "EOF") return;
      throw e;
    }
    if (n === 0) return;
    pending += buf.toString("utf8", 0, n);
    let i;
    while ((i = pending.indexOf("\n")) >= 0) {
      yield pending.slice(0, i);
      pending = pending.slice(i + 1);
    }
  }
}

function reply(obj, bytes) {
  writeSync(1, JSON.stringify(obj) + "\n");
  if (bytes) writeSync(1, Buffer.from(bytes.buffer, bytes.byteOffset, bytes.length));
}

function serve(src) {
  const m = harness(src);
  lockdown();
  const patterns = new Map();
  for (const line of lines()) {
    if (!line.trim()) continue;
    const req = JSON.parse(line);
    try {
      if (req.op === "load") {
        patterns.delete(req.key);
        const pat = new Pattern(m, req.file, req.matrix);
        if (pat.info.ok) patterns.set(req.key, pat);
        while (patterns.size > LIVE) patterns.delete(patterns.keys().next().value);
        reply(pat.info);
      } else if (req.op === "frame") {
        const pat = patterns.get(req.key);
        if (pat) {                      // the most recently used, last
          patterns.delete(req.key);
          patterns.set(req.key, pat);
        }
        const err = pat ? pat.frame(req.dt, req.d, req.p, req.h) : NOT_LOADED;
        if (err) reply({ ok: false, error: err });
        else reply({ ok: true }, pat.rgb);
      } else {
        reply({ ok: false, error: `unknown op ${req.op}` });
      }
    } catch (e) {
      reply({ ok: false, error: message(e) });
    }
  }
}

// ---- check: community.py's scripted player (see CHECK_MAIN there), at 60 fps
function check(src, id, file, name, frames, shots, out, matrix) {
  const m = harness(src);
  lockdown();
  const res = { id };
  try {
    const pat = new Pattern(m, file, matrix);
    if (!pat.info.ok) throw new Error(pat.info.error);
    Object.assign(res, { w: pat.info.w, h: pat.info.h });
    let seed = 1, ms = 0;
    const kept = [];
    for (let f = 0; f < frames; f++) {
      const phase = f < 120 ? 0 : 1 + Math.floor((f - 120) / 60), t = (f - 120) % 60;
      const d = [0, 0, 0, 0], p = [0, 0, 0, 0], h = [0, 0, 0, 0];
      for (let k = 0; k < 4; k++) {
        seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
        if (phase === 1) d[k] = 1;
        else if (phase === 2) d[k] = 8;
        else if (phase === 3) d[k] = -16;
        else if (phase === 4) d[k] = -1;
        else if (phase === 5) d[k] = (seed >>> 29) - 3;
        else if (phase === 6) { p[k] = t % 15 === 0 && Math.floor(t / 15) === k; h[k] = Math.floor(t / 15) === k; }
        else if (phase === 7) { h[k] = 1; p[k] = t === 0; d[k] = t & 1 ? 2 : -1; }
      }
      const t0 = performance.now();
      const err = pat.frame(1 / 60, d, p, h);
      ms += performance.now() - t0;
      if (err) throw new Error(`frame ${f}: ${err}`);
      if (shots.includes(f)) kept.push(Buffer.from(pat.rgb));
    }
    writeFileSync(join(out, `${id}-${name}.rgb`), Buffer.concat(kept));
    Object.assign(res, { verdict: "ok", ms: +(ms / frames).toFixed(3) });
  } catch (e) {
    res.verdict = "error: " + message(e);
  }
  writeSync(1, JSON.stringify(res) + "\n");
}

const [cmd, src, ...rest] = process.argv.slice(2);
if (cmd === "bundle") await bundle(src);
else if (cmd === "serve") serve(src);
else if (cmd === "check") {
  const [id, file, name, frames, shots, out, size] = rest;
  check(src, id, file, name, +frames, shots.split(",").map(Number), out, size ? size.split("x").map(Number) : null);
}
else {
  console.error("usage: node jsrun.mjs bundle|serve|check SRC ...");
  process.exit(2);
}
