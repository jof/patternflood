#!/usr/bin/env python3
"""Build upstream Patternflow's preset patterns into a host shared library.

The preset headers are compiled as they are, unchanged, against small host
stand-ins for the Arduino and panel headers (shim/). Upstream's portable cores
(math, colour, noise, tables, params) are used as they are too. The result is
one .so with a C API that pfd/upstream.py drives through ctypes:

    pf_count()  pf_name(i)  pf_label(i, k)  pf_author(i)  pf_width()  pf_height()
    pf_setup(i)  pf_frame(i, dt, deltas[4], pressed[4], held[4], now_ms) -> RGB888 buffer

    ./build.py                              # ../../../upstream, 128 x 128, into build/
    ./build.py --size 128x64                # upstream's own panel size, for comparison
    ./build.py --tree-only --out /tmp/pfup  # a self-contained source tree to build elsewhere (Pi 5)

The patterns are CC BY-SA 4.0 (upstream's licence). They are read from the
upstream clone at build time and are not copied into this repository.
"""
import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def default_upstream():
    """The repo's upstream/ clone. It's gitignored, so a worktree finds it in the main checkout."""
    local = HERE.parents[2] / "upstream"
    if local.exists():
        return local
    common = subprocess.run(["git", "-C", str(HERE), "rev-parse", "--path-format=absolute", "--git-common-dir"],
                            capture_output=True, text=True).stdout.strip()
    return Path(common).parent / "upstream" if common else local


CORES = ["core_math.h", "core_color.h", "core_noise.h", "core_tables.h", "core_mem.h", "core_params.h"]
SKIP = {"preset_calib.h"}       # an overlay the tuner summons, not a pattern


def presets(src):
    out = []
    for p in sorted((src / "presets").glob("preset_*.h")):
        if p.name in SKIP:
            continue
        text = p.read_text(encoding="utf-8", errors="replace")
        m = re.search(r"^namespace\s+(\w+)\s*\{", text, re.M)
        if not m:
            print(f"skip {p.name}: no namespace", file=sys.stderr)
            continue
        author = re.search(r"^//\s*Author:\s*(.+)$", text, re.M)
        out.append((p.name, m.group(1), author.group(1).strip() if author else ""))
    return out


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_tree(upstream, out):
    src = upstream / "firmware" / "patternflow"
    if out.exists():
        shutil.rmtree(out)
    (out / "src").mkdir(parents=True)
    (out / "abi").mkdir()
    shutil.copytree(src / "presets", out / "presets")
    for c in CORES:
        shutil.copy(src / "src" / c, out / "src" / c)
    shutil.copy(src / "abi" / "pf_params.h", out / "abi" / "pf_params.h")
    shutil.copytree(HERE / "shim", out, dirs_exist_ok=True)          # stand-ins win

    found = presets(src)
    rev = subprocess.run(["git", "-C", str(upstream), "rev-parse", "--short", "HEAD"],
                         capture_output=True, text=True).stdout.strip()
    lines = [f"// Generated by build.py from upstream {rev}. Do not edit.",
             '#include "Arduino.h"']
    lines += [f'#include "presets/{name}"' for name, _, _ in found]
    lines += ["",
              "struct PFHostEntry {",
              "  const char* name; const char* author; const char* const* labels;",
              "  void (*setup)(); void (*update)(float, const InputFrame&); void (*draw)();",
              "};",
              "static const PFHostEntry ENTRIES[] = {"]
    lines += [f"  {{{ns}::NAME, {c_str(author)}, {ns}::KNOB_LABELS, {ns}::setup, {ns}::update, {ns}::draw}},"
              for _, ns, author in found]
    lines += ["};",
              "static const int COUNT = sizeof(ENTRIES) / sizeof(ENTRIES[0]);",
              "static long knobs[4];",
              "",
              'extern "C" {',
              "int pf_count() { return COUNT; }",
              "int pf_width() { return PANEL_RES_W; }",
              "int pf_height() { return PANEL_RES_H; }",
              "const char* pf_name(int i) { return ENTRIES[i].name; }",
              "const char* pf_author(int i) { return ENTRIES[i].author; }",
              "const char* pf_label(int i, int k) { return ENTRIES[i].labels[k]; }",
              "void pf_setup(int i) { PFCanvas::clear(); ENTRIES[i].setup(); }",
              "const uint8_t* pf_frame(int i, float dt, const int* deltas, const uint8_t* pressed,",
              "                        const uint8_t* held, uint32_t now) {",
              "  InputFrame in;",
              "  memset(&in, 0, sizeof in);",
              "  for (int k = 0; k < 4; k++) {",
              "    knobs[k] += deltas[k];",
              "    in.knobs[k] = knobs[k];",
              "    in.knobDeltas[k] = deltas[k];",
              "    in.btnPressed[k] = pressed[k];",
              "    in.btnHeld[k] = held[k];",
              "  }",
              "  in.now = now;",
              "  pf_host_now_ms = now;",
              "  ENTRIES[i].update(dt, in);",
              "  ENTRIES[i].draw();",
              "  return PFCanvas::buffer;",
              "}",
              "}"]
    (out / "pf_host.cpp").write_text("\n".join(lines) + "\n")
    return found, rev


def compile_tree(tree, size, lib):
    w, h = size
    cmd = ["g++", "-std=c++17", "-O2", "-fPIC", "-shared", "-w",
           f"-DPANEL_RES_W={w}", f"-DPANEL_RES_H={h}",
           "-I", str(tree), "-o", str(lib), str(tree / "pf_host.cpp")]
    subprocess.run(cmd, check=True)


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0],
                                formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__)
    p.add_argument("--upstream", type=Path, default=None)
    p.add_argument("--size", default="128x128")
    p.add_argument("--out", type=Path, default=None, help="tree directory (default build/tree)")
    p.add_argument("--tree-only", action="store_true")
    args = p.parse_args()

    size = tuple(int(v) for v in args.size.lower().split("x"))
    tree = args.out or HERE / "build" / "tree"
    found, rev = write_tree(args.upstream or default_upstream(), tree)
    print(f"{len(found)} presets from upstream {rev} -> {tree}")
    if args.tree_only:
        return
    lib = HERE / "build" / f"libpfup_{size[0]}x{size[1]}.so"
    compile_tree(tree, size, lib)
    print(f"built {lib}")


if __name__ == "__main__":
    main()
